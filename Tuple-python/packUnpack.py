# unpacking a list
x, y, z = [10, 20, 30]
print(x, y, z) # 10, 20, 30
 
# unpacking a string
a, b, c, d, e = 'hello'
print(a, b, c, d, e) # h, e, l, l, o
 
# unpacking dictionary keys
k1, k2 = {'a': 1, 'b': 2}
print(k1, k2) # a, b
 
# unpacking dictionary values
v1, v2 = {'a': 1, 'b': 2}.values()
print(v1, v2) # 1, 2

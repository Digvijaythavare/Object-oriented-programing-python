# Return Boolean equivalent & Any Non-zero value is considered True
#  and only zero(0), empty string ("") is considered false
a = 33

print("Boolean  equivalent of 7 is : ",bool(a))
print("Boolean  equivalent of -7 is : ",bool(-7))
print("Boolean  equivalent of -14is : ",bool(-1))
print("Boolean  equivalent of 0.03 is : ",bool(0.03))
print("Boolean  equivalent of 2.38 is : ",bool(2.38))
print("Boolean  equivalent of 'Vijay' is : ",bool("Vijay"))
print("Boolean  equivalent of False is : ",bool(False))
print("Boolean  equivalent of Empty is : ",bool(""))
print("Boolean  equivalent of 0 is : ",bool(0))

# Union - combine elements from 2 sets

Union_set_A = {1,2,3,4,5}
Union_set_B = {4,5,6,7,8}
Set_union = Union_set_A.union(Union_set_B)
print("This is Union Set:",Set_union)


# Union alternative method
Union__A = {11,12,13,14,15}
Union__B = {14,15,16,17,18}
Set = Union__A | Union__B
print("Union Set with alernative method:",Set)
